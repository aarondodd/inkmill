#!/usr/bin/env python3
"""Build plugins/index.json from the plugin folders next to it.

Each folder under ``plugins/`` holding a ``plugin.toml`` becomes one index
entry carrying the manifest fields and a SHA-256 hash for every file. Inkmill's
plugin manager reads this index online (from the repository) or from a local
clone, and refuses any downloaded file whose hash does not match.

    python scripts/build_plugin_index.py           # rewrite the index
    python scripts/build_plugin_index.py --check   # fail if it is out of date
    python scripts/build_plugin_index.py --check --base old-index.json
        # also fail when a plugin's files changed but its version did not

Uses only the standard library so it runs anywhere Python 3.11 does.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGINS = ROOT / "plugins"
INDEX = PLUGINS / "index.json"
SKIP_DIRS = {"__pycache__", ".pytest_cache"}
SKIP_SUFFIXES = {".pyc", ".pyo"}
FIELDS = ("id", "name", "version", "requires_inkmill", "summary", "author", "license", "homepage", "external")


def plugin_files(folder: Path) -> dict[str, str]:
    files = {}
    for path in sorted(folder.rglob("*")):
        if not path.is_file() or path.suffix in SKIP_SUFFIXES:
            continue
        if any(part in SKIP_DIRS or part.startswith(".") for part in path.relative_to(folder).parts):
            continue
        files[path.relative_to(folder).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return files


def build(plugins_dir: Path = PLUGINS) -> dict:
    entries = []
    for folder in sorted(p for p in plugins_dir.iterdir() if p.is_dir() and (p / "plugin.toml").is_file()):
        manifest = tomllib.loads((folder / "plugin.toml").read_text(encoding="utf-8"))
        missing = [k for k in ("id", "name", "version") if not manifest.get(k)]
        if missing:
            raise SystemExit(f"{folder.name}/plugin.toml is missing {', '.join(missing)}")
        if manifest["id"] != folder.name:
            raise SystemExit(f"{folder.name}/plugin.toml has id {manifest['id']!r}; it must match the folder name")
        if not (folder / "__init__.py").is_file():
            raise SystemExit(f"{folder.name} has no __init__.py")
        entry = {k: manifest[k] for k in FIELDS if k in manifest}
        entry["path"] = folder.name
        entry["files"] = plugin_files(folder)
        entries.append(entry)
    return {
        "schema": 1,
        "comment": "Generated by scripts/build_plugin_index.py. Do not edit by hand.",
        "plugins": entries,
    }


def render(index: dict) -> str:
    return json.dumps(index, indent=2, sort_keys=False) + "\n"


def unbumped(new: dict, base: dict) -> list[str]:
    """Plugins whose files changed while their version stayed the same."""
    old = {p["id"]: p for p in base.get("plugins", [])}
    problems = []
    for plugin in new["plugins"]:
        before = old.get(plugin["id"])
        if before and before["files"] != plugin["files"] and before["version"] == plugin["version"]:
            problems.append(f"{plugin['id']}: files changed but version is still {plugin['version']}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if plugins/index.json is out of date")
    parser.add_argument("--base", type=Path, help="an older index to compare versions against")
    args = parser.parse_args(argv)
    index = build()
    text = render(index)
    if args.check:
        status = 0
        current = INDEX.read_text(encoding="utf-8") if INDEX.is_file() else ""
        if current != text:
            print("plugins/index.json is out of date; run python scripts/build_plugin_index.py", file=sys.stderr)
            status = 1
        if args.base and args.base.is_file() and args.base.stat().st_size:
            for problem in unbumped(index, json.loads(args.base.read_text(encoding="utf-8"))):
                print(problem, file=sys.stderr)
                status = 1
        if status == 0:
            print(f"plugins/index.json is current ({len(index['plugins'])} plugins)")
        return status
    INDEX.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(index['plugins'])} plugins)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
